// Einmalig pro autoNetzAssets-Lauf gesetzt; Cache leert sich mit jedem Lauf
let _trasseCtx = null;
const _distCache = new Map();

function _trasseDist(a, b) {
  const key = a.id < b.id ? `${a.id}|${b.id}` : `${b.id}|${a.id}`;
  if (_distCache.has(key)) return _distCache.get(key);
  const ptA = L.latLng(a.lat, a.lng);
  const ptB = L.latLng(b.lat, b.lng);
  let d;
  // Gleiche Gebäude-Assets: Direktabstand, kein Trassen-Routing
  if (a.buildingId && b.buildingId && a.buildingId === b.buildingId) {
    d = ptA.distanceTo(ptB);
  } else if (_trasseCtx) {
    const route = routeAlongTrasseWithGraph(_trasseCtx, ptA, ptB);
    d = (route && route.length >= 2) ? polylineLength(route) : ptA.distanceTo(ptB);
  } else {
    d = ptA.distanceTo(ptB);
  }
  _distCache.set(key, d);
  return d;
}

function _nearest(from, candidates) {
  let best = null, bestDist = Infinity;
  for (const c of candidates) {
    const d = _trasseDist(from, c);
    if (d < bestDist) { bestDist = d; best = c; }
  }
  return best;
}

function _geoMidpoint(assets) {
  const lat = assets.reduce((s, a) => s + a.lat, 0) / assets.length;
  const lng = assets.reduce((s, a) => s + a.lng, 0) / assets.length;
  return { lat, lng };
}

// Verbindet Verbraucher mit einem Anker.
// KVS wird eingefügt wenn: (a) Anzahl > kvsMaxConn, oder (b) Kabeldistanz > kvsMaxDistM.
function _kvsConnectZone(anchor, consumers, kvsMaxConn, kvsMaxDistM, autoKvsList) {
  // Verbraucher nach Distanz zum Anker sortieren (nächste zuerst)
  const sorted = [...consumers].sort((a, b) => _trasseDist(a, anchor) - _trasseDist(b, anchor));

  // Zu-weit-Verbraucher: Distanz > kvsMaxDistM
  const tooFar = sorted.filter(v => _trasseDist(v, anchor) > kvsMaxDistM);
  const inRange = sorted.filter(v => _trasseDist(v, anchor) <= kvsMaxDistM);

  // Überschuss durch Abgangslimit (aus den nah gelegenen)
  const directMax = Math.max(0, kvsMaxConn - (tooFar.length > 0 ? 1 : 0)); // 1 Abgang für KVS reservieren
  const direct   = inRange.slice(0, directMax);
  const overflow = [...inRange.slice(directMax), ...tooFar];

  direct.forEach(v => _addAutoEdge(anchor, v));

  if (overflow.length === 0) return;

  // KVS am Schwerpunkt der überschüssigen Verbraucher platzieren
  const mid = _geoMidpoint(overflow);
  const kvs = createAsset('KVS', mid.lat, mid.lng);
  if (!kvs) { overflow.forEach(v => _addAutoEdge(anchor, v)); return; }
  kvs.autoGenerated = true;
  drawAssetMarker(kvs);
  autoKvsList.push(kvs.id);

  overflow.forEach(v => _addAutoEdge(kvs, v));
  _addAutoEdge(anchor, kvs);
}

function _addAutoEdge(a, b, opts = {}) {
  const edge = addStromEdge(a.id, b.id);
  if (!edge) return null;
  edge.autoGenerated = true;
  if (opts.ms) {
    edge.msLevel = true;
    edge.layer?.setStyle({ color: '#ff9800', weight: 4, dashArray: null });
    edge.hitLayer?.setStyle({ weight: 18 });
  }
  if (opts.trennstelle) {
    edge.trennstelle = true;
    edge.layer?.setStyle({ dashArray: '12,8', opacity: 0.55 });
  }
  return edge;
}

