// ── Hauptfunktion ─────────────────────────────────────────────────────────────

export function autoNetzAssets(opts = {}) {
  const { ring = false, erzeugungsnetz = false, autoKvs = true, kvsMaxConn = 4, kvsMaxDistM = 80, overwriteManual = false } = opts;
  const yr = window.globalYear ?? new Date().getFullYear();

  // Graph einmalig bauen, Distanz-Cache leeren
  _trasseCtx = buildTrasseGraph();
  _distCache.clear();

  // 0. Auto-Kanten löschen (immer) — bei overwriteManual zusätzlich auch
  // manuell gezeichnete Kabel, damit das Netz komplett neu aufgebaut wird.
  // Auto-generierte KVS-Assets werden unabhängig davon immer entfernt.
  const toRemove = (window.stromEdges || []).filter(e => e.autoGenerated || overwriteManual);
  toRemove.forEach(e => removeStromEdge(e));
  ASSETS.items.filter(a => a.autoGenerated && a.type === 'KVS').forEach(a => {
    if (window.stromNodes) {
      const idx = window.stromNodes.findIndex(n => n.id === a.id);
      if (idx >= 0) window.stromNodes.splice(idx, 1);
    }
    deleteAsset(a.id);
  });

  // Assets nach Typ einsammeln
  const active = ASSETS.items.filter(a =>
    (a.domain === 'strom' || a.domain === 'hybrid') &&
    getAssetStatus(a, yr) === 'active'
  );

  const byType = t => active.filter(a => a.type === t);
  const isErzeugung = a => a.props?.netzart === 'erzeugung';

  const naps        = byType('NAP');
  const sas         = byType('Schaltanlage');
  const allTrafos   = byType('Trafo');
  const allNshvs    = byType('NSHV');
  const uvs         = byType('UV');
  const verbraucher = active.filter(a => ['Verbraucher', 'Lade', 'WP', 'Batterie'].includes(a.type));
  const erzeuger    = active.filter(a => ['PV', 'Wind', 'KWK', 'Nsa'].includes(a.type));

  // Trafos und NSHVs nach netzart aufteilen
  const erzTrafos      = allTrafos.filter(isErzeugung);
  const verbrTrafos    = allTrafos.filter(a => !isErzeugung(a));
  const trafos         = allTrafos; // für MS-Ring (alle Trafos am MS-Netz)
  const erzNshvs       = allNshvs.filter(isErzeugung);
  const verbrNshvs     = allNshvs.filter(a => !isErzeugung(a));
  const nshvs          = allNshvs; // für Fallback

  // Wenn Erzeugungstrafos vorhanden: auto. Erzeugungsnetz-Modus aktiv
  const hasErzTrafos = erzTrafos.length > 0;

  // Validierung
  const errors = [];
  if (!naps.length)   errors.push('Kein NAP vorhanden.');
  if (!sas.length)    errors.push('Keine Schaltanlage vorhanden.');
  if (!trafos.length) errors.push('Kein Trafo vorhanden.');
  if (errors.length) {
    showHint('⚠ Auto-Netz: ' + errors.join(' '));
    return;
  }

  const nap = naps[0];
  const sa  = sas[0];

  // ── 1. NAP → Schaltanlage(n) ────────────────────────────────────────────
  sas.forEach(s => _addAutoEdge(nap, s, { ms: true }));

  // ── 2. Schaltanlage → Trafos ────────────────────────────────────────────
  if (ring && trafos.length >= 2) {
    // Nearest-Neighbor-Tour: SA → T1 → T2 → ... → Tn → SA(Trennstelle)
    const remaining = [...trafos];
    const tour = [];
    let current = sa;
    while (remaining.length) {
      const next = _nearest(current, remaining);
      tour.push(next);
      remaining.splice(remaining.indexOf(next), 1);
      current = next;
    }
    _addAutoEdge(sa, tour[0], { ms: true });
    for (let i = 0; i < tour.length - 1; i++) {
      _addAutoEdge(tour[i], tour[i + 1], { ms: true });
    }
    // Ringschluss mit Trennstelle
    _addAutoEdge(tour[tour.length - 1], sa, { ms: true, trennstelle: true });
  } else {
    // Stern: SA → jeden Trafo
    trafos.forEach(t => _addAutoEdge(sa, t, { ms: true }));
  }

  // ── 3. Trafo → NSHV (netzart-getrennt) ──────────────────────────────────
  // Erzeugungsnetz-NSHVs gehen zum nächsten Erzeugungstrafo,
  // Verbrauchsnetz-NSHVs gehen zum nächsten Verbrauchstrafo.
  // Fallback: kein passender Trafo → nächster Trafo beliebiger Art.
  allNshvs.forEach(nshv => {
    const pool    = isErzeugung(nshv) ? (erzTrafos.length ? erzTrafos : allTrafos)
                                       : (verbrTrafos.length ? verbrTrafos : allTrafos);
    const nearest = _nearest(nshv, pool);
    if (nearest) _addAutoEdge(nearest, nshv);
  });

  // ── 4. NSHV → UV (Greedy-MST je NSHV-Zone, nur Verbrauchsnetz) ────────
  const uvZone = new Map();
  uvs.forEach(uv => {
    // UVs gehören immer zum Verbrauchsnetz → nur Verbrauchs-NSHVs als Anker
    const pool    = verbrNshvs.length ? verbrNshvs : allNshvs;
    const nearest = _nearest(uv, pool);
    if (nearest) uvZone.set(uv.id, nearest);
  });

  (verbrNshvs.length ? verbrNshvs : allNshvs).forEach(nshv => {
    const zoneUvs = uvs.filter(uv => uvZone.get(uv.id)?.id === nshv.id);
    if (!zoneUvs.length) return;
    const connected = new Map([[nshv.id, nshv]]);
    const remaining = [...zoneUvs];
    while (remaining.length) {
      let bestDist = Infinity, bestUv = null, bestAnchor = null;
      for (const uv of remaining) {
        for (const anchor of connected.values()) {
          const d = _trasseDist(uv, anchor);
          if (d < bestDist) { bestDist = d; bestUv = uv; bestAnchor = anchor; }
        }
      }
      if (!bestUv) break;
      _addAutoEdge(bestAnchor, bestUv);
      connected.set(bestUv.id, bestUv);
      remaining.splice(remaining.indexOf(bestUv), 1);
    }
  });

  // ── 5. UV / Verbrauchsnetz-NSHV → Verbraucher (mit optionalem KVS) ──────
  // Verbraucher werden NUR an Verbrauchsnetz-Anker gehängt, niemals an Erzeugungsnetz-NSHVs.
  const verbrAnker = [...uvs, ...(verbrNshvs.length ? verbrNshvs : allNshvs)];
  const autoKvsList = []; // IDs der automatisch platzierten KVS

  if (autoKvs) {
    // Zonen aufbauen: welcher Verbraucher gehört zu welchem Anker?
    const anchorZones = new Map();
    verbraucher.forEach(v => {
      const anchor = _nearest(v, verbrAnker);
      if (!anchor) return;
      if (!anchorZones.has(anchor.id)) anchorZones.set(anchor.id, { anchor, consumers: [] });
      anchorZones.get(anchor.id).consumers.push(v);
    });
    for (const { anchor, consumers } of anchorZones.values()) {
      _kvsConnectZone(anchor, consumers, kvsMaxConn, kvsMaxDistM, autoKvsList);
    }
    // Verbraucher ohne Anker (kein UV/NSHV vorhanden)
    verbraucher.filter(v => !Array.from(anchorZones.values()).some(z => z.consumers.includes(v)))
      .forEach(v => { const a = _nearest(v, verbrAnker); if (a) _addAutoEdge(a, v); });
  } else {
    verbraucher.forEach(v => {
      const anchor = _nearest(v, verbrAnker);
      if (anchor) _addAutoEdge(anchor, v);
    });
  }

  // ── 6. Erzeuger ──────────────────────────────────────────────────────────
  if (hasErzTrafos || erzeugungsnetz) {
    // Erzeuger → Erzeugungsnetz-NSHVs (falls vorhanden) sonst alle NSHVs
    const pool = erzNshvs.length ? erzNshvs : allNshvs;
    erzeuger.forEach(e => {
      const anchor = _nearest(e, pool);
      if (anchor) _addAutoEdge(anchor, e);
    });
  } else {
    // Standard (kein Erzeugungsnetz): Erzeuger wie Verbraucher — nächste UV oder NSHV
    erzeuger.forEach(e => {
      const anchor = _nearest(e, verbrAnker);
      if (anchor) _addAutoEdge(anchor, e);
    });
  }

  // Berechnung anstoßen (dimensioniert dabei auch die MS-Kabel, siehe elCalcAssets)
  recalcStromNetz();
  if (typeof window.elCalcAssets === 'function') window.elCalcAssets();

  const nEdges = (window.stromEdges || []).filter(e => e.autoGenerated).length;
  const kvsMsg = autoKvsList.length ? `, ${autoKvsList.length} KVS eingefügt` : '';
  showHint(`✓ Auto-Netz: ${nEdges} Kabel generiert${kvsMsg}.`);
  setTimeout(() => { if (typeof window.hideHint === 'function') window.hideHint(); }, 4000);
}
